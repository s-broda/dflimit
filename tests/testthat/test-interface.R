test_that("the shape of the input is kept and non-finite points have their limits", {
  x <- matrix(c(-Inf, -2, NaN, Inf), 2, dimnames = list(c("a", "b"), NULL))
  F <- ltratio_cdf(x, "DK")
  expect_identical(dim(F), dim(x))
  expect_identical(dimnames(F), dimnames(x))
  expect_identical(F[c(1, 3, 4)], c(0, NaN, 1))
  expect_identical(ltratio_pdf(c(-Inf, Inf), "DK"), c(0, 0))
  expect_named(ltratio_cdf(c(a = -1, b = 0), "dk"), c("a", "b"))
  expect_identical(ltratio_cdf(numeric(0), "DU"), numeric(0))
  expect_identical(adfmax_cdf(c(-Inf, NaN, Inf), "DU"), c(0, NaN, 1))
  expect_identical(dim(ltratio_icdf(matrix(c(0.05, 0.1), 1), "DK")), c(1L, 2L))
  P <- ltratio_lincdf(x, -3.5, "DK")
  expect_identical(dim(P), dim(x))
  expect_identical(dimnames(P), dimnames(x))
  expect_identical(P[c(1, 3, 4)], c(0, NaN, 1))
  expect_named(ltratio_lincdf(c(a = 0.1, b = 0.5), NaN, "dk"), c("a", "b"))
  expect_identical(ltratio_lincdf(numeric(0), 1, "DG"), numeric(0))
  E <- power_envelope(matrix(c(0, 1, NaN, 2), 2))
  expect_identical(dim(E), c(2L, 2L))
  expect_identical(E[1:3], c(0.05, 0.05, NaN))
  expect_identical(power_envelope(-7, "DU"), power_envelope(-7, "dk"))
})

test_that("errors of the engine become R errors", {
  expect_error(ltratio_cdf(0, "DU", -600), "at least -550")
  expect_error(ltratio_cdf(0, "SU", 1), "requires c <= -1e-4", fixed = TRUE)
  expect_error(ltratio_cdf(0, "DU", -5, g0 = 3), "fixed start")
  expect_error(ltratio_cdf(0, "SU", -5, g0 = 1, engine = "classical"), "applies to cases DK, DU, DT")
  expect_error(ltratio_cdf(0, "SU", -5, g0 = 1), "exclude each other")
  expect_error(ltratio_mom(2, "DG"), "not available")
  expect_error(ltratio_cdf(0, "DG", method = "double"), "single integral only")
  expect_error(ltratio_icdf(1, "DU"), "(0, 1)", fixed = TRUE)
  expect_error(ltratio_cdf(0, "DU", c = NA), "single number")
  expect_error(ltratio_cdf(0, "XX"), "the case must be")
  expect_error(ltratio_cdf(0, "DU", method = "fast"), "method must be")
  expect_error(adfmax_cdf(0, "DK"), "the case must be one of DU, DT, SU, ST")
  expect_error(ltratio_region(list(type = "fun", g = identity)), "not available")
  expect_error(ltratio_region(list(type = "line", a = 1)), "needs the element b")
  expect_error(ltratio_region(list(type = "wap", k = -1, omega = 1)), "k > 0")
  expect_error(ltratio_mom(0, "DU"), "positive integer")
  expect_error(ltratio_lincdf(0, NaN, "DG"), "case DK only")
  expect_error(ltratio_lincdf(0, 1, "DU"), "the case must be one of DK, DG")
  expect_error(ltratio_lincdf(0, NA, "DK"), "a must be a single number")
  expect_error(ltratio_lincdf(0, 1, "DK", c = Inf), "finite")
  expect_error(power_envelope(-5, "DT"), "the case must be one of DK, DU, DG")
  expect_error(power_envelope(-5, alpha = 2, engine = "classical"), "no sign change")
  expect_error(power_envelope(-5, alpha = 2), "the level must lie in (0, 1)", fixed = TRUE)
})

test_that("the number of threads can be set and does not change the values", {
  old <- ltratio_threads()
  F2 <- ltratio_cdf(c(-2, 0), "DT", -3)
  ltratio_threads(1)
  expect_identical(ltratio_threads(), 1L)
  F1 <- ltratio_cdf(c(-2, 0), "DT", -3)
  ltratio_threads(old)
  expect_identical(ltratio_threads(), old)
  expect_equal(F1, F2, tolerance = 1e-14)
  ltratio_threads(1)
  P1 <- ltratio_lincdf(c(-0.2639, 0.5), -3.5, "DK", -7)
  E1 <- power_envelope(c(-7, -13.5), "DG")
  ltratio_threads(old)
  expect_equal(ltratio_lincdf(c(-0.2639, 0.5), -3.5, "DK", -7), P1, tolerance = 1e-14)
  expect_equal(power_envelope(c(-7, -13.5), "DG"), E1, tolerance = 1e-14)
  expect_error(ltratio_threads(0), "positive integer")
})

test_that("a stationary start needs c <= -1e-4, and the values near the unit root are those of the Julia engine", {
  # for c > -1e-4 the engine refuses: the variance -1/(2c) of the start is too large for the quadrature
  msg <- "requires c <= -1e-4"
  expect_error(ltratio_cdf(-1.94087, "SK", -9e-5), msg, fixed = TRUE)
  expect_error(ltratio_pdf(-2, "SU", -9e-5), msg, fixed = TRUE)
  expect_error(ltratio_mom(2, "ST", -9e-5), msg, fixed = TRUE)
  expect_error(ltratio_icdf(0.05, "SK", -9e-5), msg, fixed = TRUE)
  expect_error(coef_cdf(-8.039, "SK", -9e-5), msg, fixed = TRUE)
  expect_error(adfmax_cdf(-2.4, "SU", -9e-5), msg, fixed = TRUE)
  # at c = -1e-4 (test/engine/quickcheck.jl of DFLimit.jl, section 18b)
  expect_lt(abs(ltratio_cdf(-1.94087, "SK", -1e-4) - 0.028490044498374834), 1e-11)
  expect_lt(abs(coef_cdf(-8.039, "SK", -1e-4) - 0.00032997244558452543), 1e-12)
  expect_lt(abs(adfmax_cdf(-2.43542, "SU", -1e-4) - 0.050000718603976146), 1e-11)
  # case SK: the coefficient statistic at c = -0.001, which the lower end of the conditional integral had put at 6e-6
  expect_lt(abs(coef_cdf(-8.039, "SK", -0.001) - 0.0010438037922007037), 1e-12)
  expect_lt(abs(ltratio_cdf(-1.94087, "SK", -0.1) - 0.059510986573375835), 1e-11)
})
